var meta = Meta{
	Version: "1.0", FeederName: "range", FeederInfo: "10.0.0.1 - 10.0.0.2",
	Time:    time.Date(2026, 1, 2, 15, 4, 5, 0, time.UTC),
	Columns: []Column{{"ip", "IP"}, {"ping", "Ping"}, {"hostname", "Hostname"}, {"ports", "Ports"}},
	Labels:  model.DefaultLabels,
}

func results() []*model.Result {
	a := netip.MustParseAddr("10.0.0.1")
	b := netip.MustParseAddr("2001:db8::1")
	return []*model.Result{
		{Addr: a, Type: model.WithPorts, MAC: "00:11:22:33:44:55", Values: []model.Value{
			model.IPValue(a), model.Millis(3), model.Text(`evil, "host" ]]> <x> & 'q' \`), model.PortsValue([]uint16{22, 80})}},
		{Addr: b, Type: model.Dead, Values: []model.Value{model.IPValue(b), model.NotAvailable, model.NotScanned, model.NotScanned}},
	}
}

func run(t *testing.T, format string, appending bool) string {
	t.Helper()
	e, err := New(format)
	if err != nil {
		t.Fatal(err)
	}
	var buf bytes.Buffer
	if err := e.Start(&buf, meta, appending); err != nil {
		t.Fatal(err)
	}
	for _, r := range results() {
		if err := e.Row(r); err != nil {
			t.Fatal(err)
		}
	}
	if err := e.End(); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

func TestTXT(t *testing.T) {
	out := run(t, "txt", false)
	lines := strings.Split(out, "\n")
	if lines[0] != "Generated by ipscan 1.0" || lines[3] != "Scanned 10.0.0.1 - 10.0.0.2" || lines[4] != "2026-01-02 15:04:05" {
		t.Errorf("header:\n%s", out)
	}
	if !strings.HasPrefix(lines[6], "IP              Ping            Hostname                Ports") {
		t.Errorf("columns: %q", lines[6])
	}
	if !strings.HasPrefix(lines[8], "2001:db8::1     [n/a]           [n/s]") {
		t.Errorf("row: %q", lines[8])
	}
	if a := run(t, "txt", true); strings.Contains(a, "Generated") || strings.Count(a, "\n") != 2 {
		t.Errorf("append:\n%s", a)
	}
	// Long values keep a two-space separator.
	if !strings.Contains(lines[7], `\  22,80`) {
		t.Errorf("long value separation: %q", lines[7])
	}
}

func TestCSV(t *testing.T) {
	recs, err := csv.NewReader(strings.NewReader(run(t, "csv", false))).ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	if len(recs) != 3 || recs[0][3] != "Ports" || recs[1][2] != `evil, "host" ]]> <x> & 'q' \` || recs[1][3] != "22,80" || recs[2][1] != "[n/a]" {
		t.Errorf("records: %q", recs)
	}
	if a := run(t, "csv", true); strings.HasPrefix(a, "IP,") {
		t.Error("append must skip header")
	}
}

func TestXML(t *testing.T) {
	out := run(t, "xml", false)
	var doc struct {
		Time   string `xml:"time,attr"`
		Feeder struct {
			Name string `xml:"name,attr"`
			Info string `xml:",chardata"`
		} `xml:"feeder"`
		Hosts []xmlHost `xml:"hosts>host"`
	}
	if err := xml.Unmarshal([]byte(out), &doc); err != nil {
		t.Fatalf("invalid XML: %v\n%s", err, out)
	}
	if doc.Time != "2026-01-02 15:04:05" || doc.Feeder.Name != "range" || doc.Feeder.Info != meta.FeederInfo || len(doc.Hosts) != 2 {
		t.Errorf("doc: %+v", doc)
	}
	if h := doc.Hosts[0]; h.Address != "10.0.0.1" || len(h.Results) != 3 || h.Results[1].Value != `evil, "host" ]]> <x> & 'q' \` {
		t.Errorf("host: %+v", h)
	}
	if len(doc.Hosts[1].Results) != 0 {
		t.Error("empty values must be omitted")
	}
	e, _ := New("xml")
	if err := e.Start(&bytes.Buffer{}, meta, true); err == nil {
		t.Error("xml append must fail")
	}
}

func TestSQL(t *testing.T) {
	out := run(t, "sql", false)
	want := []string{
		`CREATE TABLE scan ("ip" varchar(255), "ping" varchar(255), "hostname" varchar(255), "ports" varchar(255));`,
		`INSERT INTO scan VALUES ('10.0.0.1', '3 ms', 'evil, "host" ]]> <x> & ''q'' \', '22,80');`,
		`INSERT INTO scan VALUES ('2001:db8::1', NULL, NULL, NULL);`,
	}
	for _, w := range want {
		if !strings.Contains(out, w+"\n") {
			t.Errorf("missing %s in\n%s", w, out)
		}
	}
	if a := run(t, "sql", true); strings.Contains(a, "CREATE") {
		t.Error("append must skip DDL")
	}
	m := meta
	m.Columns = []Column{{`a"b`, "x"}}
	e, _ := New("sql")
	var buf bytes.Buffer
	_ = e.Start(&buf, m, false)
	_ = e.End()
	if !strings.Contains(buf.String(), `"a""b" varchar`) {
		t.Errorf("identifier escaping: %s", buf.String())
	}
}

func TestList(t *testing.T) {
	r := results()
	r[1].Values[3] = model.PortsValue([]uint16{443})
	e, _ := New("lst")
	var buf bytes.Buffer
	_ = e.Start(&buf, meta, false)
	for _, x := range r {
		_ = e.Row(x)
	}
	_ = e.End()
	if buf.String() != "10.0.0.1:22\n10.0.0.1:80\n[2001:db8::1]:443\n" {
		t.Errorf("lst = %q", buf.String())
	}
	m := meta
	m.Columns = m.Columns[:2]
	if err := e.Start(&buf, m, false); err == nil {
		t.Error("lst without ports must fail")
	}
}

func TestJSON(t *testing.T) {
	var doc struct {
		Scan  map[string]any   `json:"scan"`
		Hosts []map[string]any `json:"hosts"`
	}
	if err := json.Unmarshal([]byte(run(t, "json", false)), &doc); err != nil {
		t.Fatal(err)
	}
	h := doc.Hosts[0]
	if doc.Scan["feeder"] != "range" || len(doc.Hosts) != 2 || h["ping"] != 3.0 || h["type"] != "ports" || h["ip"] != "10.0.0.1" {
		t.Errorf("doc %+v", doc)
	}
	if ports := h["ports"].([]any); len(ports) != 2 || ports[1] != 80.0 {
		t.Errorf("ports %v", h["ports"])
	}
	if doc.Hosts[1]["ping"] != nil {
		t.Error("empty value must be null")
	}
	lines := strings.Split(strings.TrimSpace(run(t, "ndjson", false)), "\n")
	if len(lines) != 2 || !json.Valid([]byte(lines[0])) || !json.Valid([]byte(lines[1])) {
		t.Errorf("ndjson: %q", lines)
	}
}

func TestFormatFromPath(t *testing.T) {
	for in, want := range map[string]string{"a.csv": "csv", "x/y.TXT": "txt", "r.jsonl": "ndjson", "out.lst": "lst"} {
		if got, err := FormatFromPath(in); err != nil || got != want {
			t.Errorf("%s -> %s %v", in, got, err)
		}
	}
	if _, err := FormatFromPath("noext"); err == nil {
		t.Error("expected error")
	}
	if _, err := New("bogus"); err == nil {
		t.Error("expected error")
	}
}

func TestOutputAtomicAndAppend(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "scan.csv")
	o, err := Open(p, "csv", false, nil)
	if err != nil {
		t.Fatal(err)
	}
	_, _ = o.Write([]byte("IP,Ping\n"))
	if _, err := os.Stat(p); err == nil {
		t.Error("file must not exist before commit")
	}
	if err := o.Commit(); err != nil {
		t.Fatal(err)
	}
	o.Close()
	o, _ = Open(p, "csv", true, nil)
	if !o.Appending {
		t.Error("expected append mode")
	}
	_, _ = o.Write([]byte("1.2.3.4,1 ms\n"))
	_ = o.Commit()
	if b, _ := os.ReadFile(p); string(b) != "IP,Ping\n1.2.3.4,1 ms\n" {
		t.Errorf("content %q", b)
	}
	// Discard on failure.
	o, _ = Open(filepath.Join(dir, "fail.txt"), "txt", false, nil)
	o.Close()
	if entries, _ := os.ReadDir(dir); len(entries) != 1 {
		t.Errorf("temp file left behind: %v", entries)
	}
	// Refuse to append to unrelated files and symlinks.
	secret := filepath.Join(dir, "secret")
	_ = os.WriteFile(secret, []byte("password=1\n"), 0o600)
	if _, err := Open(secret, "txt", true, nil); err == nil {
		t.Error("appending to unrelated file must fail")
	}
	link := filepath.Join(dir, "link.csv")
	if os.Symlink(p, link) == nil {
		if _, err := Open(link, "csv", true, nil); err == nil {
			t.Error("appending through symlink must fail")
		}
	}
	if _, err := Open(p, "xml", true, nil); err == nil {
		t.Error("xml append must fail")
	}
	// Append to a missing file creates it.
	o, _ = Open(filepath.Join(dir, "new.txt"), "txt", true, nil)
	if o.Appending {
		t.Error("missing file must be created, not appended")
	}
	o.Close()
	var buf bytes.Buffer
	o, _ = Open("-", "csv", false, &buf)
	_, _ = o.Write([]byte("x"))
	_ = o.Commit()
	if buf.String() != "x" {
		t.Error("stdout output")
	}
}
