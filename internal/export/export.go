// Column describes one exported column.
type Column struct {
	ID   string // stable fetcher ID, e.g. "ping"
	Name string // human readable header, e.g. "Ping"
}

// Meta describes the scan being exported.
type Meta struct {
	Version    string
	FeederName string
	FeederInfo string
	Time       time.Time
	Columns    []Column
	Labels     model.Labels
}

// Exporter writes results in one format. Use Start, then Row per result, then End.
type Exporter interface {
	Start(w io.Writer, m Meta, appending bool) error
	Row(r *model.Result) error
	End() error
}

// Formats lists supported format names; they double as file extensions.
var Formats = []string{"txt", "csv", "xml", "sql", "lst", "json", "ndjson"}

// SupportsAppend reports whether the format can be appended to an existing file.
func SupportsAppend(format string) bool { return format != "xml" && format != "json" }

// New returns an exporter for the format name.
func New(format string) (Exporter, error) {
	switch strings.ToLower(format) {
	case "txt":
		return &txtExporter{}, nil
	case "csv":
		return &csvExporter{}, nil
	case "xml":
		return &xmlExporter{}, nil
	case "sql":
		return &sqlExporter{}, nil
	case "lst":
		return &listExporter{}, nil
	case "json":
		return &jsonExporter{}, nil
	case "ndjson", "jsonl":
		return &jsonExporter{lines: true}, nil
	}
	return nil, fmt.Errorf("unknown export format %q (supported: %s)", format, strings.Join(Formats, ", "))
}

// FormatFromPath derives the format from a file extension.
func FormatFromPath(path string) (string, error) {
	ext := strings.ToLower(strings.TrimPrefix(filepath.Ext(path), "."))
	if ext == "jsonl" {
		ext = "ndjson"
	}
	if !slices.Contains(Formats, ext) {
		return "", fmt.Errorf("cannot derive export format from %q; use --format (%s)", path, strings.Join(Formats, ", "))
	}
	return ext, nil
}

func cells(r *model.Result, l model.Labels) []string {
	out := make([]string, len(r.Values))
	for i, v := range r.Values {
		out[i] = v.Format(l)
	}
	return out
}

func colIndex(cols []Column, id string) int {
	return slices.IndexFunc(cols, func(c Column) bool { return c.ID == id })
}

// ---------------------------------------------------------------- TXT

// txtExporter writes the human readable Angry IP Scanner text format.
type txtExporter struct {
	w      *bufio.Writer
	m      Meta
	widths []int
}

func (e *txtExporter) Start(w io.Writer, m Meta, appending bool) error {
	e.w, e.m = bufio.NewWriter(w), m
	e.widths = make([]int, len(m.Columns))
	for i, c := range m.Columns {
		e.widths[i] = max(16, len(c.Name)*3)
	}
	if appending {
		return nil
	}
	fmt.Fprintf(e.w, "Generated by ipscan %s\nhttps://angryip.org\n\nScanned %s\n%s\n\n",
		m.Version, m.FeederInfo, m.Time.Format("2006-01-02 15:04:05"))
	names := make([]string, len(m.Columns))
	for i, c := range m.Columns {
		names[i] = c.Name
	}
	e.line(names)
	return nil
}

func (e *txtExporter) line(cells []string) {
	for i, s := range cells {
		e.w.WriteString(s)
		if i == len(cells)-1 {
			break
		}
		// always keep at least two spaces so columns stay separable
		e.w.WriteString(strings.Repeat(" ", max(2, e.widths[i]-len([]rune(s)))))
	}
	e.w.WriteByte('\n')
}

func (e *txtExporter) Row(r *model.Result) error {
	e.line(cells(r, e.m.Labels))
	return nil
}

func (e *txtExporter) End() error { return e.w.Flush() }

// ---------------------------------------------------------------- CSV

type csvExporter struct {
	w *csv.Writer
	m Meta
}

func (e *csvExporter) Start(w io.Writer, m Meta, appending bool) error {
	e.w, e.m = csv.NewWriter(w), m
	if appending {
		return nil
	}
	names := make([]string, len(m.Columns))
	for i, c := range m.Columns {
		names[i] = c.Name
	}
	return e.w.Write(names)
}

func (e *csvExporter) Row(r *model.Result) error { return e.w.Write(cells(r, e.m.Labels)) }

func (e *csvExporter) End() error {
	e.w.Flush()
	return e.w.Error()
}

// ---------------------------------------------------------------- XML

type xmlExporter struct {
	enc *xml.Encoder
	w   io.Writer
	m   Meta
}

func (e *xmlExporter) Start(w io.Writer, m Meta, appending bool) error {
	if appending {
		return fmt.Errorf("XML export does not support appending")
	}
	e.w, e.m = w, m
	if _, err := io.WriteString(w, xml.Header+"<!-- Generated by ipscan "+escapeComment(m.Version)+" -->\n"); err != nil {
		return err
	}
	e.enc = xml.NewEncoder(w)
	e.enc.Indent("", "\t")
	start := xml.StartElement{Name: xml.Name{Local: "scanning_report"},
		Attr: []xml.Attr{{Name: xml.Name{Local: "time"}, Value: m.Time.Format("2006-01-02 15:04:05")}}}
	if err := e.enc.EncodeToken(start); err != nil {
		return err
	}
	feeder := struct {
		XMLName xml.Name `xml:"feeder"`
		Name    string   `xml:"name,attr"`
		Info    string   `xml:",chardata"`
	}{Name: m.FeederName, Info: m.FeederInfo}
	if err := e.enc.Encode(feeder); err != nil {
		return err
	}
	return e.enc.EncodeToken(xml.StartElement{Name: xml.Name{Local: "hosts"}})
}

func escapeComment(s string) string { return strings.ReplaceAll(s, "--", "- -") }

type xmlResult struct {
	Name  string `xml:"name,attr"`
	Value string `xml:",chardata"`
}

type xmlHost struct {
	XMLName xml.Name    `xml:"host"`
	Address string      `xml:"address,attr"`
	Results []xmlResult `xml:"result"`
}

func (e *xmlExporter) Row(r *model.Result) error {
	h := xmlHost{Address: r.Addr.String()}
	for i, v := range r.Values {
		if i == 0 || v.IsEmpty() {
			continue
		}
		h.Results = append(h.Results, xmlResult{Name: e.m.Columns[i].Name, Value: v.Format(e.m.Labels)})
	}
	return e.enc.Encode(h)
}

func (e *xmlExporter) End() error {
	for _, n := range []string{"hosts", "scanning_report"} {
		if err := e.enc.EncodeToken(xml.EndElement{Name: xml.Name{Local: n}}); err != nil {
			return err
		}
	}
	if err := e.enc.Flush(); err != nil {
		return err
	}
	_, err := io.WriteString(e.w, "\n")
	return err
}

// ---------------------------------------------------------------- SQL

// sqlExporter writes portable SQL (standard quoting; works with SQLite,
// PostgreSQL and MySQL in ANSI_QUOTES mode). Empty values become NULL.
type sqlExporter struct {
	w *bufio.Writer
	m Meta
}

func sqlIdent(s string) string  { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
func sqlString(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func (e *sqlExporter) Start(w io.Writer, m Meta, appending bool) error {
	e.w, e.m = bufio.NewWriter(w), m
	if appending {
		return nil
	}
	cols := make([]string, len(m.Columns))
	for i, c := range m.Columns {
		cols[i] = sqlIdent(c.ID) + " varchar(255)"
	}
	fmt.Fprintf(e.w, "-- Generated by ipscan %s, scanned %s\nDROP TABLE IF EXISTS scan;\nCREATE TABLE scan (%s);\n",
		strings.ReplaceAll(m.Version, "\n", " "), strings.ReplaceAll(m.FeederInfo, "\n", " "), strings.Join(cols, ", "))
	return nil
}

func (e *sqlExporter) Row(r *model.Result) error {
	vals := make([]string, len(r.Values))
	for i, v := range r.Values {
		if v.IsEmpty() {
			vals[i] = "NULL"
		} else {
			vals[i] = sqlString(v.Format(e.m.Labels))
		}
	}
	fmt.Fprintf(e.w, "INSERT INTO scan VALUES (%s);\n", strings.Join(vals, ", "))
	return nil
}

func (e *sqlExporter) End() error { return e.w.Flush() }

// ---------------------------------------------------------------- IP list

// listExporter writes ip:port lines for every open port (hosts without open
// ports are skipped), suitable for feeding into other tools or back into ipscan.
type listExporter struct {
	w     *bufio.Writer
	ports int
}

func (e *listExporter) Start(w io.Writer, m Meta, _ bool) error {
	e.w = bufio.NewWriter(w)
	if e.ports = colIndex(m.Columns, "ports"); e.ports < 0 {
		return fmt.Errorf("the lst format requires the ports fetcher")
	}
	return nil
}

func (e *listExporter) Row(r *model.Result) error {
	v := r.Values[e.ports]
	if v.Kind != model.KindPorts {
		return nil
	}
	host := r.Addr.String()
	if r.Addr.Is6() {
		host = "[" + host + "]"
	}
	for _, p := range v.Ports {
		e.w.WriteString(host + ":" + strconv.Itoa(int(p)) + "\n")
	}
	return nil
}

func (e *listExporter) End() error { return e.w.Flush() }

// ---------------------------------------------------------------- JSON

// jsonExporter writes a JSON document ({"scan": ..., "hosts": [...]}) or, in
// lines mode, one JSON object per host (NDJSON). Keys are fetcher IDs.
type jsonExporter struct {
	lines bool
	w     *bufio.Writer
	m     Meta
	n     int
}

func (e *jsonExporter) Start(w io.Writer, m Meta, appending bool) error {
	if appending && !e.lines {
		return fmt.Errorf("JSON export does not support appending; use ndjson")
	}
	e.w, e.m = bufio.NewWriter(w), m
	if e.lines {
		return nil
	}
	head, err := json.Marshal(map[string]any{
		"generator": "ipscan " + m.Version, "feeder": m.FeederName, "info": m.FeederInfo,
		"time": m.Time.Format(time.RFC3339), "columns": m.Columns,
	})
	if err != nil {
		return err
	}
	fmt.Fprintf(e.w, "{\"scan\":%s,\"hosts\":[", head)
	return nil
}

func (c Column) MarshalJSON() ([]byte, error) {
	return json.Marshal(map[string]string{"id": c.ID, "name": c.Name})
}

func (e *jsonExporter) Row(r *model.Result) error {
	obj := make([]byte, 0, 128)
	obj = append(obj, `{"type":`...)
	obj = strconv.AppendQuote(obj, r.Type.String())
	if r.MAC != "" {
		obj = append(obj, `,"mac_raw":`...)
		obj = strconv.AppendQuote(obj, r.MAC)
	}
	for i, v := range r.Values {
		b, err := json.Marshal(v)
		if err != nil {
			return err
		}
		key, _ := json.Marshal(e.m.Columns[i].ID)
		obj = append(append(append(append(obj, ','), key...), ':'), b...)
	}
	obj = append(obj, '}')
	switch {
	case e.lines:
		obj = append(obj, '\n')
	case e.n > 0:
		e.w.WriteByte(',')
	}
	e.n++
	_, err := e.w.Write(obj)
	return err
}

func (e *jsonExporter) End() error {
	if !e.lines {
		e.w.WriteString("]}\n")
	}
	return e.w.Flush()
}
