package export

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// Output is a destination for an export. Close must be called; Commit makes
// the result visible (for new files written atomically via a temp file).
type Output struct {
	io.Writer
	Appending bool
	file      *os.File
	tmp       string
	final     string
}

// Open prepares the output. "-" means stdout. A new file is written to a
// temporary file and renamed on Commit, so a failed scan never leaves a
// partial file behind. Appending requires an existing regular file (no
// symlinks) whose content looks like the same format.
func Open(path, format string, appending bool, stdout io.Writer) (*Output, error) {
	if path == "-" {
		return &Output{Writer: stdout}, nil
	}
	if appending {
		if !SupportsAppend(format) {
			return nil, fmt.Errorf("format %s does not support appending", format)
		}
		fi, err := os.Lstat(path)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			appending = false // nothing to append to: create the file normally
		case err != nil:
			return nil, err
		case !fi.Mode().IsRegular():
			return nil, fmt.Errorf("refusing to append to %s: not a regular file", path)
		default:
			if err := checkSameFormat(path, format); err != nil {
				return nil, err
			}
			f, err := os.OpenFile(path, os.O_WRONLY|os.O_APPEND, 0)
			if err != nil {
				return nil, err
			}
			return &Output{Writer: f, Appending: true, file: f}, nil
		}
	}
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".*.tmp")
	if err != nil {
		return nil, err
	}
	return &Output{Writer: f, file: f, tmp: f.Name(), final: path}, nil
}

// checkSameFormat sniffs the head of an existing file to avoid appending scan
// results to unrelated (possibly sensitive) files.
func checkSameFormat(path, format string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	head, _ := bufio.NewReader(f).Peek(512)
	s := string(head)
	ok := len(head) == 0
	switch format {
	case "txt":
		ok = ok || strings.HasPrefix(s, "Generated by ")
	case "sql":
		ok = ok || strings.HasPrefix(s, "-- Generated by ipscan") || strings.HasPrefix(s, "DROP TABLE IF EXISTS scan") || strings.HasPrefix(s, "INSERT INTO scan")
	case "ndjson":
		ok = ok || strings.HasPrefix(s, `{"type":`)
	case "csv":
		ok = ok || strings.HasPrefix(s, "IP,") || strings.HasPrefix(s, "IP\n")
	case "lst":
		ok = ok || strings.Contains(strings.SplitN(s, "\n", 2)[0], ":")
	}
	if !ok {
		return fmt.Errorf("refusing to append to %s: it does not look like an ipscan %s export", path, format)
	}
	return nil
}

// Commit finalises a successful export.
func (o *Output) Commit() error {
	if o.file == nil {
		return nil
	}
	if err := o.file.Sync(); err != nil {
		return err
	}
	if err := o.file.Close(); err != nil {
		return err
	}
	o.file = nil
	if o.tmp != "" {
		_ = os.Chmod(o.tmp, 0o644)
		return os.Rename(o.tmp, o.final)
	}
	return nil
}

// Close releases resources; without Commit, a new file is discarded.
func (o *Output) Close() error {
	if o.file == nil {
		return nil
	}
	err := o.file.Close()
	o.file = nil
	if o.tmp != "" {
		_ = os.Remove(o.tmp)
	}
	return err
}
